#!/usr/bin/env bash
# Regenerate src/vendor/openscreen-schema.ts from an OpenScreen release tag.
set -euo pipefail
TAG="${1:-v1.12.2}"
URL="https://raw.githubusercontent.com/getopenscreen/openscreen/$TAG/src/lib/ai-edition/schema/index.ts"
OUT="src/vendor/openscreen-schema.ts"
mkdir -p src/vendor
{
	echo "// GENERATED by scripts/vendor-schema.sh from getopenscreen/openscreen@$TAG"
	echo "// (src/lib/ai-edition/schema/index.ts). Do not edit; re-run the script instead."
	curl -fsSL "$URL" | sed \
		-e 's#from "../../../utils/aspectRatioUtils"#from "./shims"#' \
		-e 's#from "../document/ids"#from "./shims"#' \
		-e 's#from "../timeline/timelineMap"#from "./shims"#'
} >"$OUT"
count=$(grep -c 'from "./shims"' "$OUT" || true)
if [ "$count" -ne 3 ]; then
	echo "expected 3 shim imports, found $count — upstream imports changed" >&2
	exit 1
fi
echo "wrote $OUT from $TAG"
